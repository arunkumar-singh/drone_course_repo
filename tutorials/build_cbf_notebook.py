                "class CBFSafetyFilter:\n",
                "    \"\"\"\n",
                "    Control Barrier Function (CBF) Safety Filter for Single-Integrator Navigation.\n",
                "    Directly implements the pointwise optimal QP closed-form solution from docs/cbf_drone.pdf.\n",
                "    \"\"\"\n",
                "    def __init__(self, obstacles, D_obs=0.42, alpha=2.5, v_max=1.8):\n",
                "        \"\"\"\n",
                "        Parameters:\n",
                "            obstacles: List of 3D obstacle center positions [ [x, y, z], ... ]\n",
                "            D_obs: Safety buffer distance (obstacle radius + drone safety margin)\n",
                "            alpha: Class-K gain parameter (controls aggressiveness of the barrier boundary)\n",
                "            v_max: Maximum velocity limit (m/s)\n",
                "        \"\"\"\n",
                "        self.obstacles = [np.array(obs, dtype=np.float32) for obs in obstacles]\n",
                "        self.D_obs = D_obs\n",
                "        self.alpha = alpha\n",
                "        self.v_max = v_max\n",
                "\n",
                "    def filter(self, v_des, current_pos):\n",
                "        \"\"\"\n",
                "        Applies the CBF safety filter onto the nominal velocity v_des.\n",
                "        Returns:\n",
                "            v_safe: Filtered safe velocity command\n",
                "            min_h: Minimum barrier value across all obstacles\n",
                "            active_psi: Safety margin indicator for the most critical obstacle\n",
                "        \"\"\"\n",
                "        current_pos = np.array(current_pos, dtype=np.float32)\n",
                "        v_cmd = v_des.copy()\n",
                "\n",
                "        min_h = 999.0\n",
                "        active_psi = 999.0\n",
                "\n",
                "        # Evaluate barrier constraints across all obstacles\n",
                "        for p_obs in self.obstacles:\n",
                "            diff = current_pos - p_obs\n",
                "            dist = np.linalg.norm(diff)\n",
                "\n",
                "            if dist < 1e-4:\n",
                "                normal = np.array([1.0, 0.0, 0.0], dtype=np.float32)\n",
                "            else:\n",
                "                normal = diff / dist\n",
                "\n",
                "            # Barrier function value h(p)\n",
                "            h = dist - self.D_obs\n",
                "            if h < min_h:\n",
                "                min_h = h\n",
                "\n",
                "            # Safety margin Psi = ∇h^T v_des + alpha * h\n",
                "            psi = np.dot(normal, v_cmd) + self.alpha * h\n",
                "            if psi < active_psi:\n",
                "                active_psi = psi\n",
                "\n",
                "            # If safety constraint is violated, apply closed-form projection (Eq. 16 & 19)\n",
                "            if psi < 0.0:\n",
                "                # Analytical minimal-invasive correction\n",
                "                v_correction = -psi * normal\n",
                "                v_cmd = v_cmd + v_correction\n",
                "\n",
                "                # Circumvention Circulation: If approaching directly head-on, add a gentle\n",
                "                # transverse velocity component perpendicular to normal to prevent stalling\n",
                "                collinearity = abs(np.dot(normal, v_des) / (np.linalg.norm(v_des) + 1e-6))\n",
                "                if collinearity > 0.85 and h < 0.25:\n",
                "                    tangent = np.array([-normal[1], normal[0], 0.1], dtype=np.float32)\n",
                "                    norm_tangent = np.linalg.norm(tangent)\n",
                "                    if norm_tangent > 1e-4:\n",
                "                        tangent = tangent / norm_tangent\n",
                "                        v_cmd = v_cmd + 0.35 * tangent\n",
                "\n",
                "        # Enforce maximum speed saturation\n",
                "        speed = np.linalg.norm(v_cmd)\n",
                "        if speed > self.v_max:\n",
                "            v_cmd = v_cmd * (self.v_max / speed)\n",
                "\n",
                "        return v_cmd.astype(np.float32), min_h, active_psi\n",
                "\n",
                "print(\"CBFSafetyFilter class successfully defined!\")"
