                "        # Headless offscreen renderer\n",
                "        self.renderer = mujoco.Renderer(self.model, 540, 720)\n",
                "\n",
                "    def _quat_to_euler(self, q):\n",
                "        w, x, y, z = q\n",
                "        sinr_cosp = 2.0 * (w * x + y * z)\n",
                "        cosr_cosp = 1.0 - 2.0 * (x * x + y * y)\n",
                "        roll = np.arctan2(sinr_cosp, cosr_cosp)\n",
                "\n",
